// Academic Calendar events - code-managed list mirroring the printed 2026-2028 calendar.
//
// Each entry has a title, a start date (YYYY-MM-DD, local), an optional endDate for
// multi-day ranges, and a term label used for grouping/context in the calendar sidebar.
// Items listed as "TBD" on the printed calendar are intentionally omitted here since
// they have no assignable date.

export interface AcademicEvent {
  title: string
  /** Start date in YYYY-MM-DD (local). */
  date: string
  /** Optional end date in YYYY-MM-DD for multi-day items. */
  endDate?: string
  /** Term / section label, e.g. "Spring Semester 2026". */
  term: string
}

type Raw = [title: string, date: string, endDate?: string]

function term(name: string, items: Raw[]): AcademicEvent[] {
  return items.map(([title, date, endDate]) => ({ title, date, endDate, term: name }))
}

